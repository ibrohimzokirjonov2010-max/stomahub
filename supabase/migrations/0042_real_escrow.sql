-- 12. Admin: “Sotuvchiga to‘lov” (qo‘lda bank o‘tkazmasi)
-- ---------------------------------------------------------------------------
create or replace function public.admin_seller_payouts(p_tab text default 'kutilmoqda', p_q text default '', p_page int default 1, p_page_size int default 10)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_page int := greatest(1, coalesce(p_page, 1));
  v_size int := least(50, greatest(1, coalesce(p_page_size, 10)));
  v_q text := lower(trim(coalesce(p_q, '')));
  v jsonb;
begin
  if not public.is_admin() then raise exception 'Faqat admin'; end if;
  with g as (
    select l.seller_id,
           coalesce(nullif(p.shop_name, ''), p.name) as shop_name,
           coalesce(ss.legal, '{}'::jsonb) as legal,
           sum(l.amount - l.paid_amount) filter (where l.status = 'kutilmoqda') as due,
           count(*) filter (where l.status = 'kutilmoqda') as due_orders,
           sum(l.paid_amount) as paid,
           sum(l.commission) as commission,
           max(l.paid_at) as last_paid_at,
           max(l.released_at) as last_released_at
      from public.seller_payout_ledger l
      join public.profiles p on p.id = l.seller_id
      left join public.seller_settings ss on ss.seller_id = l.seller_id
     group by l.seller_id, p.shop_name, p.name, ss.legal
  ), f as (
    select * from g where (p_tab = 'all' or (p_tab = 'kutilmoqda' and coalesce(due, 0) > 0) or (p_tab = 'tolandi' and coalesce(due, 0) = 0))
      and (v_q = '' or lower(coalesce(shop_name, '')) like '%' || v_q || '%')
  )
  select jsonb_build_object(
    'summary', jsonb_build_object(
      'due', coalesce((select sum(amount - paid_amount) from public.seller_payout_ledger where status = 'kutilmoqda'), 0),
      'due_sellers', (select count(distinct seller_id) from public.seller_payout_ledger where status = 'kutilmoqda'),
      'paid', coalesce((select sum(paid_amount) from public.seller_payout_ledger), 0),
      'commission', coalesce((select sum(commission) from public.seller_payout_ledger), 0)),
    'total', (select count(*) from f), 'page', v_page, 'page_size', v_size,
    'rows', coalesce((select jsonb_agg(row_to_json(x)::jsonb) from (
       select f.seller_id, f.shop_name, coalesce(f.due, 0) as due, f.due_orders, coalesce(f.paid, 0) as paid, f.commission,
              f.last_paid_at, f.last_released_at,
              f.legal->>'bank' as bank, f.legal->>'mfo' as mfo, f.legal->>'account' as account, f.legal->>'stir' as stir,
              (select coalesce(jsonb_agg(jsonb_build_object('id', l.id, 'code', o.code, 'amount', l.amount - l.paid_amount,
                        'commission', l.commission, 'gross', l.gross, 'released_at', l.released_at, 'reason', l.release_reason)
                        order by l.released_at), '[]'::jsonb)
                 from public.seller_payout_ledger l join public.seller_orders o on o.id = l.order_id
                where l.seller_id = f.seller_id and l.status = 'kutilmoqda') as items
         from f order by coalesce(f.due, 0) desc, f.last_released_at desc
        limit v_size offset (v_page - 1) * v_size) x), '[]'::jsonb)
  ) into v;
  return v;
end $$;
revoke all on function public.admin_seller_payouts(text, text, int, int) from public, anon;
grant execute on function public.admin_seller_payouts(text, text, int, int) to authenticated;

