-- 4. Holatga qarab to‘lov holati (barcha rollar uchun, guard'dan keyin ishlaydi: nom tartibi a < b)
-- ---------------------------------------------------------------------------
create or replace function public.seller_orders_pay_flow()
returns trigger language plpgsql set search_path = public as $$
declare v_cash boolean := coalesce(new.payment_method, 'cash') in ('cash', 'naqd');
begin
  if new.status is not distinct from old.status then return new; end if;

  if new.status = 'yetkazildi' then
    new.delivered_at := coalesce(new.delivered_at, now());
    if v_cash and new.payment_status = 'pending' then
      new.payment_status := 'paid';   -- naqd: yetkazilganda to‘landi
    end if;
  elsif new.status = 'bekor_qilindi' then
    if v_cash then
      if new.payment_status = 'pending' then new.payment_status := 'failed'; end if;
    elsif new.payment_status in ('held', 'paid') then
      new.payment_status := 'refund_pending';   -- pul xaridorga qaytarilishi kerak
      new.escrow_refund_reason := coalesce(nullif(new.escrow_refund_reason, ''), nullif(new.cancel_reason, ''), 'Buyurtma bekor qilindi');
    elsif new.payment_status = 'pending' then
      new.payment_status := 'failed';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists seller_orders_b_pay_flow on public.seller_orders;
create trigger seller_orders_b_pay_flow
  before update of status on public.seller_orders
  for each row execute function public.seller_orders_pay_flow();

-- ---------------------------------------------------------------------------
-- 5. Ichki release (ledger yozadi) — to‘g‘ridan-to‘g‘ri chaqirib bo‘lmaydi
-- ---------------------------------------------------------------------------
create or replace function public.escrow_release_internal(p_order uuid, p_by uuid, p_reason text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v public.seller_orders;
  v_net numeric; v_comm numeric; v_gross numeric;
begin
  select * into v from public.seller_orders where id = p_order for update;
  if not found then raise exception 'Buyurtma topilmadi'; end if;
  if v.payment_status = 'released' then
    return jsonb_build_object('ok', true, 'idempotent', true, 'id', v.id);
  end if;
  if v.payment_status not in ('held', 'paid') or coalesce(v.payment_method, 'cash') in ('cash', 'naqd') then
    raise exception 'Escrowda turgan onlayn to‘lov emas';
  end if;
  if v.status = 'bekor_qilindi' then raise exception 'Bekor qilingan buyurtmani chiqarib bo‘lmaydi'; end if;

  v_net := greatest(v.subtotal - coalesce(v.discount_amount, 0), 0);
  v_comm := round(v_net * coalesce(v.commission_rate, 0.12));
  v_gross := v_net + coalesce(v.delivery_fee, 0);

  update public.seller_orders set
    status = case when status = 'yetkazilmoqda' then 'yetkazildi' else status end,
    delivered_at = coalesce(delivered_at, now()),
    payment_status = 'released',
    escrow_released_at = now(),
    escrow_released_by = p_by,
    dispute_status = case when dispute_status = 'open' then 'resolved_release' else dispute_status end,
    dispute_resolved_at = case when dispute_status = 'open' then now() else dispute_resolved_at end,
    updated_at = now()
  where id = p_order;

  insert into public.seller_payout_ledger (order_id, seller_id, gross, commission, amount, released_by, release_reason)
  values (v.id, v.seller_id, v_gross, v_comm, v_gross - v_comm, p_by, left(coalesce(p_reason, ''), 120))
  on conflict (order_id) do nothing;

  insert into public.customer_notifications (user_id, kind, title, body, link)
  values (v.seller_id, 'order', 'Escrow chiqarildi',
    'Buyurtma ' || v.code || ': ' || (v_gross - v_comm)::text || ' so‘m to‘lovga tayyor', '/sotuvchi/hamyon');

  return jsonb_build_object('ok', true, 'id', v.id, 'code', v.code, 'amount', v_gross - v_comm, 'commission', v_comm);
end $$;
revoke all on function public.escrow_release_internal(uuid, uuid, text) from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 6. payment_mark_paid — FAQAT server (service_role) chaqiradi: Click/Payme imzosi tekshirilgach.
--    Onlayn buyurtma → 'held' (Escrowda). Mijoz tomonidan hech qachon 'paid' bo‘lmaydi.
-- ---------------------------------------------------------------------------
create or replace function public.payment_mark_paid(
  p_provider text, p_merchant_trans_id text, p_provider_trans_id text, p_amount numeric,
  p_order_id uuid default null, p_registration_id text default null, p_meta jsonb default '{}'::jsonb
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_tx public.payment_transactions;
  v_order public.seller_orders;
  v_provider text := lower(trim(coalesce(p_provider, '')));
  v_due numeric;
begin
  if v_provider not in ('click', 'payme') then raise exception 'Noto‘g‘ri provayder'; end if;

  select * into v_tx from public.payment_transactions
   where provider = v_provider and merchant_trans_id = p_merchant_trans_id and state in ('created', 'pending', 'paid')
   order by created_at desc limit 1 for update;
  if found and v_tx.state = 'paid' then
    return jsonb_build_object('ok', true, 'idempotent', true, 'id', v_tx.id, 'seq', v_tx.seq, 'state', 'paid');
  end if;

  if p_order_id is not null then
    select * into v_order from public.seller_orders where id = p_order_id for update;
    if not found then raise exception 'Buyurtma topilmadi'; end if;
    if v_order.status = 'bekor_qilindi' then raise exception 'Buyurtma bekor qilingan'; end if;
    if v_order.payment_status not in ('pending', 'failed') then raise exception 'Buyurtma allaqachon to‘langan'; end if;
    v_due := greatest(v_order.subtotal - coalesce(v_order.discount_amount, 0), 0) + coalesce(v_order.delivery_fee, 0);
    if p_amount is null or abs(p_amount - v_due) > 0.5 then raise exception 'Summa mos kelmaydi'; end if;
  end if;

  if v_tx.id is not null then
    update public.payment_transactions set
      provider_trans_id = coalesce(nullif(p_provider_trans_id, ''), provider_trans_id),
      amount = coalesce(p_amount, amount), state = 'paid', perform_time = now(),
      order_id = coalesce(p_order_id, order_id), registration_id = coalesce(p_registration_id, registration_id),
      meta = coalesce(meta, '{}'::jsonb) || coalesce(p_meta, '{}'::jsonb), updated_at = now()
    where id = v_tx.id returning * into v_tx;
  else
    insert into public.payment_transactions (provider, provider_trans_id, merchant_trans_id, order_id, registration_id,
      buyer_id, seller_id, amount, commission, payout, state, perform_time, meta)
    values (v_provider, coalesce(p_provider_trans_id, ''), p_merchant_trans_id, p_order_id, p_registration_id,
      v_order.buyer_id, v_order.seller_id, coalesce(p_amount, 0), 0, 0, 'paid', now(), coalesce(p_meta, '{}'::jsonb))
    returning * into v_tx;
  end if;

  if p_order_id is not null then
    update public.seller_orders set
      payment_status = 'held',
      payment_method = v_provider,
      payment_ref = left(coalesce(nullif(p_provider_trans_id, ''), p_merchant_trans_id), 64),
      updated_at = now()
    where id = p_order_id;
    insert into public.customer_notifications (user_id, kind, title, body, link) values
      (v_order.buyer_id, 'order', 'To‘lov qabul qilindi', 'Buyurtma ' || v_order.code || ': pul escrowda saqlanmoqda', '/profil/buyurtmalar'),
      (v_order.seller_id, 'order', 'Buyurtma to‘landi', 'Buyurtma ' || v_order.code || ' onlayn to‘landi (escrow). Yuborishingiz mumkin', '/sotuvchi/buyurtmalar');
  end if;

  if p_registration_id is not null then
    update public.registrations set pay = 'paid' where id = p_registration_id and coalesce(pay, '') <> 'paid';
  end if;

  return jsonb_build_object('ok', true, 'id', v_tx.id, 'seq', v_tx.seq, 'state', 'paid', 'order_id', p_order_id);
end $$;
revoke all on function public.payment_mark_paid(text, text, text, numeric, uuid, text, jsonb) from public, anon, authenticated;
grant execute on function public.payment_mark_paid(text, text, text, numeric, uuid, text, jsonb) to service_role;

-- Pul xaridorga haqiqatda qaytarildi (Payme CancelTransaction -2, Click reversal muvaffaqiyatli) — service_role
create or replace function public.payment_mark_refunded(p_order uuid, p_method text, p_note text default '')
returns jsonb language plpgsql security definer set search_path = public as $$
declare v public.seller_orders;
begin
  select * into v from public.seller_orders where id = p_order for update;
  if not found then raise exception 'Buyurtma topilmadi'; end if;
  if v.payment_status = 'released' then raise exception 'Chiqarilgan to‘lovni qaytarib bo‘lmaydi'; end if;
  if v.payment_status = 'refunded' then return jsonb_build_object('ok', true, 'idempotent', true); end if;
  update public.seller_orders set
    status = case when status in ('yetkazildi', 'bekor_qilindi') then status else 'bekor_qilindi' end,
    cancel_reason = coalesce(nullif(cancel_reason, ''), 'To‘lov qaytarildi'),
    payment_status = 'refunded',
    refund_method = left(coalesce(p_method, ''), 30),
    escrow_refunded_at = now(),
    escrow_refund_reason = coalesce(nullif(escrow_refund_reason, ''), left(coalesce(p_note, ''), 300)),
    dispute_status = case when dispute_status = 'open' then 'resolved_refund' else dispute_status end,
    dispute_resolved_at = case when dispute_status = 'open' then now() else dispute_resolved_at end,
    updated_at = now()
  where id = p_order;
  update public.payment_transactions set state = 'refunded', cancel_time = coalesce(cancel_time, now()), updated_at = now()
   where order_id = p_order and state = 'paid';
  if v.buyer_id is not null then
    insert into public.customer_notifications (user_id, kind, title, body, link)
    values (v.buyer_id, 'order', 'Pul qaytarildi', 'Buyurtma ' || v.code || ' uchun to‘lov qaytarildi', '/profil/buyurtmalar');
  end if;
  return jsonb_build_object('ok', true, 'id', p_order, 'payment_status', 'refunded');
end $$;
revoke all on function public.payment_mark_refunded(uuid, text, text) from public, anon, authenticated;
grant execute on function public.payment_mark_refunded(uuid, text, text) to service_role;

-- ---------------------------------------------------------------------------
-- 7. Xaridor: “Qabul qildim” va “Muammo bor”
-- ---------------------------------------------------------------------------
create or replace function public.buyer_confirm_receipt(p_order uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v public.seller_orders;
begin
  if auth.uid() is null then raise exception 'Avtorizatsiya kerak'; end if;
  select * into v from public.seller_orders where id = p_order and buyer_id = auth.uid() for update;
  if not found then raise exception 'Buyurtma topilmadi'; end if;
  if v.dispute_status = 'open' then raise exception 'Nizo ochiq — admin hal qiladi'; end if;
  if v.status not in ('yetkazilmoqda', 'yetkazildi') then raise exception 'Buyurtma hali yetkazilmagan'; end if;
  update public.seller_orders set buyer_confirmed_at = now(), updated_at = now() where id = p_order;
  if v.payment_status in ('held', 'paid') and coalesce(v.payment_method, 'cash') not in ('cash', 'naqd') then
    return public.escrow_release_internal(p_order, auth.uid(), 'buyer_confirm');
  end if;
  if v.status <> 'yetkazildi' then
    update public.seller_orders set status = 'yetkazildi', updated_at = now() where id = p_order;
  end if;
  return jsonb_build_object('ok', true, 'id', p_order);
end $$;
revoke all on function public.buyer_confirm_receipt(uuid) from public, anon;
grant execute on function public.buyer_confirm_receipt(uuid) to authenticated;

create or replace function public.buyer_open_dispute(p_order uuid, p_reason text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v public.seller_orders; v_reason text := left(trim(coalesce(p_reason, '')), 500);
begin
  if auth.uid() is null then raise exception 'Avtorizatsiya kerak'; end if;
  if length(v_reason) < 5 then raise exception 'Muammoni qisqacha yozing (kamida 5 belgi)'; end if;
  select * into v from public.seller_orders where id = p_order and buyer_id = auth.uid() for update;
  if not found then raise exception 'Buyurtma topilmadi'; end if;
  if v.payment_status not in ('held', 'paid') or coalesce(v.payment_method, 'cash') in ('cash', 'naqd') then
    raise exception 'Nizo faqat escrowdagi onlayn to‘lov uchun ochiladi';
  end if;
  if v.dispute_status = 'open' then return jsonb_build_object('ok', true, 'idempotent', true); end if;
  update public.seller_orders set dispute_status = 'open', dispute_reason = v_reason, dispute_opened_at = now(), updated_at = now()
   where id = p_order;
  insert into public.customer_notifications (user_id, kind, title, body, link)
  values (v.seller_id, 'order', 'Xaridor muammo bildirdi', 'Buyurtma ' || v.code || ': ' || v_reason, '/sotuvchi/buyurtmalar');
  return jsonb_build_object('ok', true, 'id', p_order, 'dispute_status', 'open');
end $$;
revoke all on function public.buyer_open_dispute(uuid, text) from public, anon;
grant execute on function public.buyer_open_dispute(uuid, text) to authenticated;

-- ---------------------------------------------------------------------------
-- 8. Avto-chiqarish (Vercel cron → /api/cron/escrow-release, service_role)
-- ---------------------------------------------------------------------------
create or replace function public.escrow_auto_release(p_days int default 3)
returns jsonb language plpgsql security definer set search_path = public as $$
declare r record; v_n int := 0; v_ids jsonb := '[]'::jsonb; v_days int := greatest(1, least(30, coalesce(p_days, 3)));
begin
  for r in
    select o.id, o.code from public.seller_orders o
     where o.payment_status = 'held' and o.status = 'yetkazildi' and o.dispute_status <> 'open'
       and coalesce(o.payment_method, 'cash') not in ('cash', 'naqd')
       and coalesce(o.delivered_at, o.updated_at) < now() - make_interval(days => v_days)
       and not public.order_is_demo(o)
     order by o.delivered_at limit 200
  loop
    perform public.escrow_release_internal(r.id, null, 'auto_' || v_days || 'd');
    v_n := v_n + 1; v_ids := v_ids || to_jsonb(r.code);
  end loop;
  return jsonb_build_object('ok', true, 'released', v_n, 'codes', v_ids, 'days', v_days);
end $$;
revoke all on function public.escrow_auto_release(int) from public, anon, authenticated;
grant execute on function public.escrow_auto_release(int) to service_role;

