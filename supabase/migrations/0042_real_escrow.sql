-- ---------------------------------------------------------------------------
-- 11. Sotuvchi hamyoni (real ma’lumot): escrowda / mavjud / to‘langan
-- ---------------------------------------------------------------------------
create or replace function public.seller_wallet()
returns jsonb language sql stable security definer set search_path = public as $$
  with l as (select * from public.seller_payout_ledger where seller_id = auth.uid()),
  v as (
    select
      coalesce((select sum(amount) from l), 0) as earned,
      coalesce((select sum(paid_amount) from l), 0) as paid_out,
      coalesce((select sum(greatest(o.subtotal - coalesce(o.discount_amount, 0), 0) + coalesce(o.delivery_fee, 0)
                       - round(greatest(o.subtotal - coalesce(o.discount_amount, 0), 0) * coalesce(o.commission_rate, 0.12)))
                  from public.seller_orders o
                 where o.seller_id = auth.uid() and o.payment_status in ('held', 'paid')
                   and coalesce(o.payment_method, 'cash') not in ('cash', 'naqd')), 0) as held,
      coalesce((select sum(amount) from public.seller_payouts where seller_id = auth.uid() and status = 'kutilmoqda'), 0) as requested,
      coalesce((select sum(amount) from public.seller_payouts where seller_id = auth.uid() and status = 'tolandi' and not ledger_allocated), 0) as legacy_paid,
      coalesce((select sum(amount) from public.seller_ad_topups where seller_id = auth.uid()), 0) as ads,
      coalesce((select sum(commission) from public.seller_orders where seller_id = auth.uid() and status = 'yetkazildi'
                 and coalesce(payment_method, 'cash') in ('cash', 'naqd')), 0) as commission_owed,
      (select count(*) from public.seller_orders where seller_id = auth.uid() and dispute_status = 'open') as disputes
  )
  select jsonb_build_object(
    'earned', earned, 'held', held, 'pending', held, 'paid_out', paid_out + legacy_paid,
    'available', greatest(0, earned - paid_out - legacy_paid - requested - ads),
    'requested', requested, 'commission_owed', commission_owed, 'disputes', disputes,
    -- seller_payout_guard: earned − withdrawn
    'withdrawn', paid_out + legacy_paid + requested + ads
  ) from v;
$$;
grant execute on function public.seller_wallet() to authenticated;

