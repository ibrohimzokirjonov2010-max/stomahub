-- 0042_real_escrow.sql — haqiqiy escrow (Click / Payme) + naqd to‘lov oqimi + sotuvchiga to‘lov reestri.
-- QO‘LDA QO‘LLANADI (Supabase SQL editor). Idempotent. 0041 (seller auto customers) bilan to‘qnashmaydi.
--
-- Oqim:
--   Naqd  : pending (Kutilmoqda) → yetkazildi bo‘lganda paid (To‘landi) + 12% komissiya; bekor → failed.
--   Onlayn: pending → (Click Complete / Payme PerformTransaction, server tomonda imzo tekshirilgach)
--           payment_mark_paid → held (Escrowda) → xaridor “Qabul qildim” yoki yetkazildidan N kun o‘tib
--           escrow_auto_release (cron) → released (Chiqarildi) → seller_payout_ledger ga yozuv.
--           “Muammo bor” → dispute_status='open' → avto-chiqarish to‘xtaydi → admin release/refund qiladi.
--           Bekor / refund → refund_pending (qo‘lda yoki Click reversal / Payme kabinet) → refunded.
-- Xavfsizlik: sotuvchi (authenticated) seller_orders da faqat holat/izoh/kuzatuv maydonlarini o‘zgartira oladi;
--   to‘lov, escrow, summa, komissiya maydonlari faqat SECURITY DEFINER funksiyalar orqali o‘zgaradi.

