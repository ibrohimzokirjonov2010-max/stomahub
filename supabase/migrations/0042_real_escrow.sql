-- Sotuvchi so‘rovini tasdiqlash → reestrdagi eng eski ochiq yozuvlarga FIFO taqsimlanadi.
create or replace function public.admin_review_payout(p_id uuid, p_action text, p_reason text default '')
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_p public.seller_payouts; v_left numeric; r record; v_take numeric;
begin
  if not public.is_admin() then raise exception 'Faqat admin'; end if;
  if p_action not in ('approve','reject') then raise exception 'Noto‘g‘ri amal'; end if;
  if p_action = 'reject' and length(trim(coalesce(p_reason,''))) < 3 then raise exception 'Rad etish sababini yozing'; end if;
  update public.seller_payouts set
    status = case when p_action = 'approve' then 'tolandi' else 'rad_etildi' end,
    reject_reason = case when p_action = 'reject' then trim(p_reason) else reject_reason end,
    reviewed_at = now(), reviewed_by = auth.uid(),
    ledger_allocated = (p_action = 'approve')
  where id = p_id and status = 'kutilmoqda'
  returning * into v_p;
  if not found then raise exception 'To‘lov so‘rovi topilmadi yoki allaqachon ko‘rib chiqilgan'; end if;
  if p_action = 'approve' then
    v_left := v_p.amount;
    for r in select * from public.seller_payout_ledger where seller_id = v_p.seller_id and status = 'kutilmoqda'
              order by released_at for update loop
      exit when v_left <= 0;
      v_take := least(v_left, r.amount - r.paid_amount);
      update public.seller_payout_ledger set paid_amount = paid_amount + v_take,
        status = case when paid_amount + v_take >= amount then 'tolandi' else status end,
        paid_at = now(), paid_by = auth.uid(), bank_ref = 'so‘rov:' || left(p_id::text, 8)
      where id = r.id;
      v_left := v_left - v_take;
    end loop;
  end if;
  return jsonb_build_object('ok', true, 'action', p_action);
end $$;
grant execute on function public.admin_review_payout(uuid, text, text) to authenticated;

-- ---------------------------------------------------------------------------
-- 13. Hisobotlar: escrow / chiqarilgan / naqd bir xil manbadan, demo chiqarib tashlanadi.
--     Komissiya faqat release (onlayn) yoki yetkazildi+paid (naqd) paytida hisoblanadi.
-- ---------------------------------------------------------------------------
create or replace function public.admin_money(p_from timestamptz, p_to timestamptz)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_from timestamptz := coalesce(p_from, date_trunc('month', now()));
  v_to timestamptz := coalesce(p_to, now());
  v_pct numeric := coalesce((select commission_pct from public.admin_settings where id = 'main'), 12);
  v jsonb;
begin
  if not public.is_admin() then raise exception 'Faqat admin'; end if;
  with allo as (
    select x.*, public.order_is_demo(x) as demo, coalesce(x.payment_method, '') in ('cash', 'naqd') as is_cash,
           greatest(x.subtotal - coalesce(x.discount_amount, 0), 0) as net
      from public.seller_orders x
  ), o as (select * from allo where created_at between v_from and v_to),
  led as (select l.* from public.seller_payout_ledger l join allo a on a.id = l.order_id and not a.demo),
  sem as (
    select r.id, coalesce(t.price, 0) as price
      from public.registrations r
      left join public.tickets t on t.id = r.ticket_id
        or (r.ticket_id is null and t.seminar_id = r.seminar_id and t.name = r.ticket)
     where r.pay = 'paid' and r.created_at between v_from and v_to
  )
  select jsonb_build_object(
    'orders_count', (select count(*) from o),
    'orders_cancelled', (select count(*) from o where status = 'bekor_qilindi'),
    'orders_demo', (select count(*) from o where demo),
    'turnover', coalesce((select sum(subtotal) from o where status <> 'bekor_qilindi' and not demo), 0),
    'turnover_delivered', coalesce((select sum(subtotal) from o where status = 'yetkazildi' and not demo), 0),
    -- komissiya: onlayn — release paytida (ledger), naqd — yetkazildi & paid
    'commission', coalesce((select sum(commission) from led where released_at between v_from and v_to), 0)
                + coalesce((select sum(commission) from allo where is_cash and not demo and status = 'yetkazildi'
                             and payment_status = 'paid' and coalesce(delivered_at, updated_at) between v_from and v_to), 0),
    'commission_online', coalesce((select sum(commission) from led where released_at between v_from and v_to), 0),
    'commission_cash', coalesce((select sum(commission) from allo where is_cash and not demo and status = 'yetkazildi'
                             and payment_status = 'paid' and coalesce(delivered_at, updated_at) between v_from and v_to), 0),
