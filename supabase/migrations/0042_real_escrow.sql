-- 3. Himoya triggeri: sotuvchi/xaridor (authenticated) to‘lov maydonlarini o‘zgartira olmaydi
-- ---------------------------------------------------------------------------
create or replace function public.seller_orders_money_guard()
returns trigger language plpgsql set search_path = public as $$
declare
  -- authenticated rolga ruxsat etilgan maydonlar (qolgan hammasi muzlatilgan)
  v_allowed text[] := array['status', 'cancel_reason', 'internal_note', 'tracking_url', 'updated_at',
    'status_history', 'commission', 'payout', 'customer_name', 'customer_phone', 'address', 'city',
    'region', 'contact_person', 'delivery_date', 'lat', 'lng', 'note', 'customer_id'];
  v_old jsonb; v_new jsonb; k text;
begin
  -- SECURITY DEFINER funksiyalar ichida current_user = egasi (postgres) → cheklov yo‘q.
  if current_user not in ('authenticated', 'anon') or public.is_admin() then
    return case when tg_op = 'DELETE' then old else new end;
  end if;

  if tg_op = 'INSERT' then
    raise exception 'Buyurtma faqat rasmiy oqim orqali yaratiladi';
  end if;
  if tg_op = 'DELETE' then
    if old.payment_status not in ('pending', 'failed') or old.source <> 'manual' then
      raise exception 'Bu buyurtmani o‘chirib bo‘lmaydi';
    end if;
    return old;
  end if;

  v_old := to_jsonb(old); v_new := to_jsonb(new);
  for k in select jsonb_object_keys(v_new) loop
    if not (k = any (v_allowed)) and (v_new -> k) is distinct from (v_old -> k) then
      raise exception 'Bu maydonni o‘zgartirishga ruxsat yo‘q: %', k;
    end if;
  end loop;

  if new.status is distinct from old.status then
    if old.dispute_status = 'open' then
      raise exception 'Nizo ochiq: holatni faqat admin o‘zgartira oladi';
    end if;
    if coalesce(old.payment_method, 'cash') not in ('cash', 'naqd')
       and old.payment_status = 'pending' and new.status <> 'bekor_qilindi' then
      raise exception 'Onlayn to‘lov hali tasdiqlanmagan';
    end if;
    if old.payment_status in ('released', 'refunded', 'refund_pending') then
      raise exception 'To‘lovi yopilgan buyurtma holatini o‘zgartirib bo‘lmaydi';
    end if;
  end if;
  return new;
end $$;

drop trigger if exists seller_orders_a_money_guard on public.seller_orders;
create trigger seller_orders_a_money_guard
  before insert or update or delete on public.seller_orders
  for each row execute function public.seller_orders_money_guard();

