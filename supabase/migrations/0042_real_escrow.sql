-- Refund: onlayn to‘lovni 'refund_pending' ga o‘tkazadi. Pulni qaytarish:
--   Click  → admin paneldan /api/click (reversal) → payment_mark_refunded
--   Payme  → merchant kabinetida bekor qilinadi → Payme CancelTransaction → payment_mark_refunded
--   Boshqa → admin_escrow_mark_refunded (qo‘lda qaytarildi deb belgilash)
create or replace function public.admin_escrow_refund(p_order uuid, p_reason text default '')
returns jsonb language plpgsql security definer set search_path = public as $$
declare v public.seller_orders; v_reason text := coalesce(nullif(left(trim(coalesce(p_reason, '')), 300), ''), 'Admin qaytarish');
begin
  if not public.is_admin() then raise exception 'Faqat admin'; end if;
  select * into v from public.seller_orders where id = p_order for update;
  if not found then raise exception 'Buyurtma topilmadi'; end if;
  if v.payment_status = 'released' then raise exception 'Chiqarilgan escrowni qaytarib bo‘lmaydi'; end if;
  if v.payment_status in ('refunded', 'refund_pending') then
    return jsonb_build_object('ok', true, 'idempotent', true, 'id', p_order, 'payment_status', v.payment_status, 'provider', v.payment_method);
  end if;
  if coalesce(v.payment_method, 'cash') in ('cash', 'naqd') or v.payment_status not in ('held', 'paid') then
    raise exception 'Qaytariladigan onlayn to‘lov yo‘q';
  end if;
  update public.seller_orders set
    escrow_refund_reason = v_reason,
    cancel_reason = coalesce(nullif(cancel_reason, ''), v_reason),
    status = case when status in ('yetkazildi', 'bekor_qilindi') then status else 'bekor_qilindi' end,
    payment_status = 'refund_pending',
    dispute_status = case when dispute_status = 'open' then 'resolved_refund' else dispute_status end,
    dispute_resolved_at = case when dispute_status = 'open' then now() else dispute_resolved_at end,
    updated_at = now()
  where id = p_order;
  return jsonb_build_object('ok', true, 'id', p_order, 'code', v.code, 'payment_status', 'refund_pending', 'provider', v.payment_method);
end $$;
revoke all on function public.admin_escrow_refund(uuid, text) from public, anon;
